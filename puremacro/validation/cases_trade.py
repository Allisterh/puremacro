"""Validation cases for the trade model on the bundled OECD ICIO table.

The bundled table (``puremacro.trade.data.load_icio_data()``, built by
``tools/build_icio_isic.py`` from the OECD ICIO 2023 edition, reference year
2019) sums the native file's 77 economies and 45 activities into the G20
countries plus a rest of the world and the 20 ISIC Rev.4 sections. Three
properties can be checked against something outside the model: the
aggregation must conserve the world totals of the native OECD file, every
industry column must balance with positive value added, and the calibrated
model must reproduce the base year as its own zero-tariff equilibrium.
"""
from __future__ import annotations

from functools import lru_cache

import numpy as np

from puremacro.validation._model import Mechanism, Tol, ValidationCase

_SUBSYSTEM = "Trade"
_OECD = ("OECD (2023), OECD Inter-Country Input-Output Tables, http://oe.cd/icio; "
         "2019_SML.csv, MD5 28cba31491177955445051d459053744")

# Sums over the native 2019_SML.csv (77 economies x 45 activities), read with
# puremacro.trade._oecd_icio.read_native: the VA row, and every intermediate and
# final sale (the table sets output to row sales). Current million USD.
# self-generated by puremacro 5.1.0 on 2019_SML.csv; not an external reference
# (fixture: OECD ICIO 2023 edition, 2019_SML.csv MD5 28cba31491177955445051d459053744)
_NATIVE_TOTALS = {"world_value_added": 81589615.1063, "world_gross_output": 170744698.0953}


@lru_cache(maxsize=1)
def _bundled():
    from puremacro.trade.data import load_icio_data

    return load_icio_data(return_structured=True)


def _dims() -> tuple[int, int, int]:
    t = _bundled()
    return len(t.country_codes), len(t.sector_codes), len(t.fd_codes)


def _world_totals() -> dict:
    nc, ns, _ = _dims()
    n = nc * ns
    M = _bundled().matrix
    return {"world_value_added": float(M[n + 1:n + 3, :n].sum()), "world_gross_output": float(M[:n].sum())}


def _column_balance() -> dict:
    """max_j |sales_j - purchases_j - taxes_j - VA_j| / sales_j over the producing industry columns."""
    nc, ns, _ = _dims()
    n = nc * ns
    M = _bundled().matrix
    sales = M[:n].sum(axis=1)
    outlays = M[:n, :n].sum(axis=0) + M[n, :n] + M[n + 1, :n] + M[n + 2, :n]
    producing = sales > 0
    va = M[n + 1, :n] + M[n + 2, :n]
    return {"max_relative_imbalance": float(np.max(np.abs(sales - outlays)[producing] / sales[producing])),
            "non_positive_value_added_cells": float(np.sum(va <= 0))}


@lru_cache(maxsize=1)
def _base_solution():
    from puremacro.trade import calibrate_trade_model, solve_trade_equilibrium

    calib = calibrate_trade_model(_bundled().matrix, validate=True)
    return solve_trade_equilibrium(calib, method="newton", tol=2.5e-3)


def _base_is_calibration_point() -> dict:
    res = _base_solution()
    return {
        "max_abs_log_price": float(np.max(np.abs(np.log(res.p_sol)))),
        "max_abs_log_wage": float(np.max(np.abs(np.log(res.w_sol)))),
        "max_abs_log_rental": float(np.max(np.abs(np.log(res.r_sol)))),
        "converged": float(res.converged),
    }


CASES: list[ValidationCase] = [
    ValidationCase(
        id="trade.oecd_isic_aggregation_conserves_native_world_totals",
        subsystem=_SUBSYSTEM,
        title="Bundled OECD ICIO table (G20 + ROW, ISIC sections): world value added and gross output equal the native OECD file's",
        title_es="Tabla OCDE ICIO incluida (G20 + RDM, secciones CIIU): el valor agregado y la producción bruta mundiales igualan los del archivo nativo de la OCDE",
        mechanism=Mechanism.INTERNAL,
        compute=_world_totals,
        reference=lambda: dict(_NATIVE_TOTALS),
        tol=Tol.TIGHT,
        citation=_OECD,
        notes="The native totals are sums over the 3,465 country-activity rows of 2019_SML.csv; summing "
              "countries into ROW and activities into sections must move cells, not create or destroy "
              "value. Output is measured as row sales, which the table's builder uses as output.",
    ),
    ValidationCase(
        id="trade.oecd_isic_columns_balance_and_value_added_is_positive",
        subsystem=_SUBSYSTEM,
        title="Bundled OECD ICIO table: every producing industry column balances (sales = purchases + taxes + value added) with positive value added",
        title_es="Tabla OCDE ICIO incluida: cada columna industrial productiva cuadra (ventas = compras + impuestos + valor agregado) con valor agregado positivo",
        mechanism=Mechanism.INTERNAL,
        compute=_column_balance,
        reference=lambda: {"max_relative_imbalance": 0.0, "non_positive_value_added_cells": 0.0},
        tol=Tol.TIGHT,
        citation=_OECD,
        notes="Net taxes are the accounting residual of the aggregation, so the identity holds to rounding; "
              "the case also pins that no country-sector has non-positive value added (zero-output nodes "
              "carry the regularization's value-added floor).",
    ),
    ValidationCase(
        id="trade.oecd_isic_base_equilibrium_is_the_calibration_point",
        subsystem=_SUBSYSTEM,
        title="Bundled OECD ICIO table: the calibrated model's zero-tariff equilibrium is the base year (unit prices, wages and rentals)",
        title_es="Tabla OCDE ICIO incluida: el equilibrio sin aranceles del modelo calibrado es el año base (precios, salarios y rentas unitarios)",
        mechanism=Mechanism.INTERNAL,
        compute=_base_is_calibration_point,
        reference=lambda: {"max_abs_log_price": 0.0, "max_abs_log_wage": 0.0, "max_abs_log_rental": 0.0, "converged": 1.0},
        tol=Tol.TIGHT,
        citation="calibrate_trade_model / solve_trade_equilibrium (puremacro.trade), Newton, tol 2.5e-3",
        notes="Calibration reproduces the data, so the equilibrium system evaluated at unit prices is "
              "already within tolerance and the solver accepts the starting point.",
    ),
]
