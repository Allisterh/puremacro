def _n_total(calib):
    return 2 * calib.n_sectors * calib.n_countries + 4 * calib.n_countries - 1


@pytest.fixture(scope="module")
def synthetic_2c_2s_calib():
    """Construct balanced 2-country 2-sector synthetic calibration."""
    nc, ns, nfd = 2, 2, 3
    data = np.zeros((ns * nc + 3, ns * nc + nfd * nc), dtype=float)
    data[:4, :4] = np.array([
        [10.0, 15.0, 5.0, 5.0],
        [15.0, 20.0, 10.0, 10.0],
        [5.0, 5.0, 12.0, 18.0],
        [10.0, 10.0, 18.0, 22.0],
    ])
    inter_col_sums = data[:4, :4].sum(axis=0)
    y = np.array([100.0, 150.0, 120.0, 180.0])
    va = y - inter_col_sums
    taxes = 0.05 * y
    va_fac = va - taxes
    labor = (2.0 / 3.0) * va_fac
    capital = (1.0 / 3.0) * va_fac
    data[4, :4] = taxes
    data[5, :4] = labor
    data[6, :4] = capital
    inter_row_sums = data[:4, :4].sum(axis=1)
    fd_row_sums = y - inter_row_sums
    for i in range(4):
        tot_fd = fd_row_sums[i]
        if i < 2:
            data[i, 4:10] = [tot_fd * 0.50, tot_fd * 0.25, tot_fd * 0.05, tot_fd * 0.10, tot_fd * 0.08, tot_fd * 0.02]
        else:
            data[i, 4:10] = [tot_fd * 0.10, tot_fd * 0.08, tot_fd * 0.02, tot_fd * 0.50, tot_fd * 0.25, tot_fd * 0.05]
    data[4, 4:] = 0.02 * data[:4, 4:].sum(axis=0)
    return calibrate_trade_model(data, ns=ns, nc=nc, nfd=nfd, validate=True)


class TestSparsityPatternAndDensity:
    """1. Sparsity pattern density and valid CSC format on the large and the small synthetic tables."""

    def test_icio_sparsity_pattern_type_and_shape(self, large_calib):
        N = _n_total(large_calib)
        S = _build_cge_sparsity_pattern(large_calib)
        assert sp.isspmatrix_csc(S), "Pattern must be scipy.sparse.csc_matrix"
        assert S.shape == (N, N)

    def test_icio_sparsity_pattern_density_pinned(self, large_calib):
        S = _build_cge_sparsity_pattern(large_calib)
        N = S.shape[0]
        density = S.nnz / (N * N)
        assert density == pytest.approx(SYNTHETIC_70X12_DENSITY, abs=5e-4)

    def test_icio_dynamic_sparsity_activation_preserves_density_bound(self, large_calib):
        ns, nc = large_calib.n_sectors, large_calib.n_countries
        M = ns * nc
        N = 2 * M + 4 * nc - 1

        # sigma_y active: only the M diagonal entries of the y-block are added
        S_base = _build_cge_sparsity_pattern(large_calib)
        S_sig = _build_cge_sparsity_pattern(large_calib, sigma_y=0.5)
        d_sig = S_sig.nnz / (N * N)
        assert d_sig <= S_base.nnz / (N * N) + M / (N * N) + 1e-15
        assert sp.isspmatrix_csc(S_sig)
        blk_sig = S_sig[M : 2 * M, M : 2 * M].toarray()
        assert np.all(np.diag(blk_sig))
        assert np.count_nonzero(blk_sig) == M

        # variable markups active
        S_mkt = _build_cge_sparsity_pattern(large_calib, variable_markups=True)
        d_mkt = S_mkt.nnz / (N * N)
        assert d_mkt <= S_base.nnz / (N * N) + M / (N * N) + 1e-15
        assert sp.isspmatrix_csc(S_mkt)
        blk_mkt = S_mkt[M : 2 * M, M : 2 * M].toarray()
        assert np.all(np.diag(blk_mkt))

    def test_synthetic_sparsity_density_under_bound(self, synthetic_2c_2s_calib):
        S = _build_cge_sparsity_pattern(synthetic_2c_2s_calib)
        N = S.shape[0]
        density = S.nnz / (N * N)
        assert density < 0.60, f"Synthetic density {density} exceeds 0.60"
        assert sp.isspmatrix_csc(S)


class TestSolverEfficiencyAndConvergence:
    """2. Solver efficiency at default calibration: converges in <= 2 outer iterations."""

    def test_solve_flexible_trade_equilibrium_converges_le_2_iterations(self, large_calib):
        res = solve_flexible_trade_equilibrium(large_calib, tol=2.5e-3, max_iter=50)
        assert res.converged, "Flexible solver failed to converge at default calibration"
        assert res.iterations <= 2, f"Outer iterations {res.iterations} exceeded 2"
        assert res.residual_norm <= 2.5e-3

    def test_quasi_condensed_solve_converges_le_2_iterations_lapack(self, large_calib):
        res = solve_flexible_trade_equilibrium(
            large_calib, method="quasi_condensed", tol=2.5e-3, max_iter=50
        )
        assert res.converged, "Quasi-condensed solver failed to converge at default calibration"
        assert res.iterations <= 2, f"Outer iterations {res.iterations} exceeded 2"
        assert res.residual_norm <= 2.5e-3

    def test_solution_vector_matches_baseline(self, large_calib):
        res_flex = solve_flexible_trade_equilibrium(large_calib, tol=2.5e-3, max_iter=50)
        res_base = solve_trade_equilibrium(large_calib, tol=2.5e-3, max_iter=50)
        max_diff = float(np.max(np.abs(res_flex.x_sol - res_base.x_sol)))
        assert max_diff <= 5.0e-4, f"Solution difference {max_diff} exceeded 5.0e-4"


class TestBaselineCalibrationInvariance:
    """3. Exact baseline calibration invariance: ||F_flex(x0) - F_base(x0)||_infty <= 10^-10."""

    def test_baseline_residual_invariance_at_x0(self, large_calib):
        x0 = build_initial_guess(large_calib)
        f_base = compute_equilibrium_residuals(x0, large_calib)
        res_0 = solve_flexible_trade_equilibrium(large_calib, max_iter=0)
        f_flex = res_0.residuals
        max_diff = float(np.max(np.abs(f_flex - f_base)))
        assert max_diff <= 1e-10, f"||F_flex(x0) - F_base(x0)||_infty = {max_diff} exceeds 1e-10"

    def test_baseline_residual_invariance_default_solve(self, large_calib):
        x0 = build_initial_guess(large_calib)
        f_base = compute_equilibrium_residuals(x0, large_calib)
        res_def = solve_flexible_trade_equilibrium(large_calib)
        f_flex = res_def.residuals
        max_diff = float(np.max(np.abs(f_flex - f_base)))
        assert max_diff <= 1e-10, f"||F_flex(x0) - F_base(x0)||_infty = {max_diff} exceeds 1e-10"

    def test_smooth_subsistence_scaling_machine_precision(self):
        val = smooth_subsistence_scaling(1.0)
        diff = abs(val - 1.0)
        assert diff <= 1e-15, f"g(1.0) deviation {diff} exceeds 1e-15"


class TestStateVectorPreservation:
    """4. Confirm the state vector length 2M + 4nc - 1 is preserved across all operations."""

    def test_initial_guess_length(self, large_calib):
        x0 = build_initial_guess(large_calib)
        assert len(x0) == _n_total(large_calib)

    def test_solution_vector_length(self, large_calib):
        res = solve_flexible_trade_equilibrium(large_calib)
        assert len(res.x_sol) == _n_total(large_calib)

    def test_unpack_equilibrium_vector_shapes(self, large_calib):
        x0 = build_initial_guess(large_calib)
        ns, nc = large_calib.n_sectors, large_calib.n_countries
        vars0 = unpack_equilibrium_vector(x0, ns=ns, nc=nc)
        assert vars0.p.shape == (1, 12, 70)
        assert vars0.y.shape == (1, 12, 70)
        assert vars0.r.shape == (1, 1, 70)
        assert vars0.w.shape == (1, 1, 70)
        assert vars0.T.shape == (1, 1, 70)
        assert vars0.XN.shape == (69,)
        assert vars0.invforT.shape == (1, 70)
        # Sum of parts = 2 * ns * nc + 3 * nc + (nc - 1)
        total_len = vars0.p.size + vars0.y.size + vars0.r.size + vars0.w.size + vars0.T.size + vars0.XN.size
        assert total_len == _n_total(large_calib)
