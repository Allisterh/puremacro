"""Milestone 4 verification: large-table calibration invariance and solver efficiency (Challenger 2).

Runs on a seeded synthetic table with 70 countries and 12 sectors
(``synthetic_icio_table(70, 12, seed=4)``) and a small 2x2 table. Verifies:
1. Sparsity pattern density and valid CSC format:
   - Density pinned on the synthetic table (self-generated; the synthetic
     table has no zero flows, so its pattern is denser than a real table's).
   - Dynamic activation of S[M:2M, M:2M] when sigma_y >= 1e-6 or variable_markups=True.
   - CSC matrix type, shape (2M + 4nc - 1, 2M + 4nc - 1).
   - Density < 0.60 on the small synthetic model (2c x 2s).
2. Solver efficiency at the benchmark calibration:
   - solve_flexible_trade_equilibrium converges in <= 2 outer iterations.
   - Quasi-condensed solver converges in <= 2 outer iterations.
   - Solution vector matches the baseline solution vector within 5.0e-4.
3. Exact baseline calibration invariance:
   - ||F_flex(x0) - F_base(x0)||_infty <= 10^-10.
   - Smooth subsistence scaling |g(1.0) - 1.0| <= 10^-15.
4. General equilibrium state vector dimension preservation:
   - Length 2M + 4nc - 1 across initial guess, solver solution, and flexible configurations.
   - Unpacking into 6 economic variable tensors preserves exact physical dimensions.
"""
