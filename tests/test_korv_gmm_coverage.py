class TestBuildUsercostColumn:
    def _make_price_panel(self, n_per: int = 20) -> pd.DataFrame:
        rng = np.random.default_rng(7)
        codes = ['US', 'DE']
        rows = []
        for code in codes:
            p_k = np.cumprod(1 + 0.01 * rng.standard_normal(n_per))
            for t in range(n_per):
                rows.append({'code': code, 'year': 2000 + t, 'p_k': p_k[t]})
        return pd.DataFrame(rows)

    def test_returns_series_aligned_to_panel(self):
        panel = self._make_price_panel()
        result = build_usercost_column(panel)
        assert isinstance(result, pd.Series)
        assert len(result) == len(panel)
        assert result.name == 'log_r_e'

    def test_last_obs_per_country_is_nan(self):
        """Forward diff: last observation within each country must be NaN."""
        panel = self._make_price_panel(n_per=15)
        result = build_usercost_column(panel)
        panel_with_uc = panel.copy()
        panel_with_uc['log_r_e'] = result.values
        for code in ['US', 'DE']:
            last_val = panel_with_uc[panel_with_uc['code'] == code]['log_r_e'].iloc[-1]
            assert np.isnan(last_val), (
                f"Last obs for {code} should be NaN (forward diff undefined)"
            )

    def test_with_r_col(self):
        """Passing r_col uses per-row interest rate."""
        panel = self._make_price_panel()
        panel['r_rate'] = 0.04
        result = build_usercost_column(panel, r_col='r_rate')
        result_default = build_usercost_column(panel, r_bar=0.04)
        # Should be identical since r_rate == r_bar everywhere
        mask = ~(result.isna() | result_default.isna())
        np.testing.assert_allclose(
            result[mask].to_numpy(), result_default[mask].to_numpy(), rtol=1e-10
        )

    def test_large_depreciation_increases_usercost(self):
        """Higher δ_e raises the user cost (cap_factor = r + δ - E[ΔlogP_K])."""
        panel = self._make_price_panel()
        uc_low  = build_usercost_column(panel, delta_e=0.05)
        uc_high = build_usercost_column(panel, delta_e=0.20)
        mask = ~(uc_low.isna() | uc_high.isna())
        # Higher depreciation → higher user cost → higher log_r_e
        assert (uc_high[mask] > uc_low[mask]).all(), (
            "Higher δ_e should increase log user cost"
        )


