class TestMoments:
    def test_output_shape(self):
        """_moments must return (n_obs, 3) array."""
        df = _make_korv_panel(n=30)
        dat = {c: df[c].to_numpy() for c in
               ('dlog_ls_lu', 'dlog_ws_wu', 'dlog_ke_lu',
                'dlog_wu_pk', 'dlog_lsushare', 'dlog_pk_pc')}
        theta = np.array([0.7, 1.5])
        out = _moments(theta, dat)
        assert out.shape == (30, 3)

    def test_near_zero_at_true_params(self):
        """With noise=0, mean of moment conditions must be near zero at DGP params."""
        df = _make_korv_panel(n=500, sigma_su=0.7, sigma_eu=1.5, noise=0.0)
        dat = {c: df[c].to_numpy() for c in
               ('dlog_ls_lu', 'dlog_ws_wu', 'dlog_ke_lu',
                'dlog_wu_pk', 'dlog_lsushare', 'dlog_pk_pc')}
        theta_true = np.array([0.7, 1.5])
        g_bar = _moments(theta_true, dat).mean(axis=0)
        # Exact-identification means moments are not identically zero
        # but they should be much smaller than at wrong params
        theta_wrong = np.array([1.5, 0.5])
        g_bar_wrong = _moments(theta_wrong, dat).mean(axis=0)
        assert np.linalg.norm(g_bar) < np.linalg.norm(g_bar_wrong), (
            "Moments at true params should be smaller in norm than at wrong params"
        )


