class TestAllenSigmaEs:
    def test_cd_limit_equal_elasticities(self):
        """When σ_su == σ_eu, the harmonic mean equals both."""
        for s in [0.5, 0.7, 1.2, 2.0]:
            result = _allen_sigma_es(s, s, 0.4)
            assert abs(result - s) < 1e-12, f"expected {s}, got {result}"

    def test_harmonic_between_min_max(self):
        """Harmonic mean must lie strictly between min(σ) and max(σ)."""
        sigma_su, sigma_eu = 0.5, 2.0
        for share in [0.1, 0.3, 0.5, 0.7, 0.9]:
            result = _allen_sigma_es(sigma_su, sigma_eu, share)
            assert min(sigma_su, sigma_eu) < result < max(sigma_su, sigma_eu), (
                f"share={share}: result={result} not strictly between "
                f"{sigma_su} and {sigma_eu}"
            )

    def test_monotone_in_share(self):
        """As equipment share rises toward 1, σ_es approaches σ_eu."""
        sigma_su, sigma_eu = 0.5, 2.0
        shares = np.linspace(0.01, 0.99, 20)
        values = [_allen_sigma_es(sigma_su, sigma_eu, s) for s in shares]
        # When share_e -> 1: harmonic mean = 1/(1/sigma_eu + 0/sigma_su) = sigma_eu
        # When share_e -> 0: harmonic mean -> sigma_su
        assert values[-1] > values[0], "sigma_es should increase with share_e"

    def test_degenerate_share_clipped(self):
        """share values outside (0,1) should be clipped without crashing."""
        # Should not raise; just return a valid float
        result_zero  = _allen_sigma_es(0.5, 1.5, 0.0)
        result_one   = _allen_sigma_es(0.5, 1.5, 1.0)
        result_neg   = _allen_sigma_es(0.5, 1.5, -0.5)
        result_large = _allen_sigma_es(0.5, 1.5, 5.0)
        for val in [result_zero, result_one, result_neg, result_large]:
            assert np.isfinite(val), f"expected finite, got {val}"

    def test_known_value(self):
        """Verify formula: 1 / (0.5/σ_eu + 0.5/σ_su)."""
        sigma_su, sigma_eu, share = 0.5, 2.0, 0.5
        expected = 1.0 / (0.5 / sigma_eu + 0.5 / sigma_su)
        result = _allen_sigma_es(sigma_su, sigma_eu, share)
        assert abs(result - expected) < 1e-12


