class TestGmmObjective:
    def test_returns_scalar_nonneg(self):
        """GMM objective must be a non-negative scalar."""
        df = _make_korv_panel(n=30)
        dat = {c: df[c].to_numpy() for c in
               ('dlog_ls_lu', 'dlog_ws_wu', 'dlog_ke_lu',
                'dlog_wu_pk', 'dlog_lsushare', 'dlog_pk_pc')}
        theta = np.array([0.7, 1.5])
        W = np.eye(3)
        val = _gmm_objective(theta, dat, W)
        assert isinstance(val, float)
        assert val >= 0.0

    def test_2mom_returns_scalar_nonneg(self):
        df = _make_korv_panel(n=30)
        dat = {c: df[c].to_numpy() for c in
               ('dlog_ls_lu', 'dlog_ws_wu', 'dlog_ke_lu', 'dlog_wu_pk')}
        theta = np.array([0.7, 1.5])
        W = np.eye(2)
        val = _gmm_objective_2mom(theta, dat, W)
        assert isinstance(val, float)
        assert val >= 0.0

    def test_identity_weight_equals_quadratic_form(self):
        """With W=I, objective must equal ||g_bar||^2."""
        df = _make_korv_panel(n=40)
        dat = {c: df[c].to_numpy() for c in
               ('dlog_ls_lu', 'dlog_ws_wu', 'dlog_ke_lu',
                'dlog_wu_pk', 'dlog_lsushare', 'dlog_pk_pc')}
        theta = np.array([0.9, 1.1])
        g_bar = _moments(theta, dat).mean(axis=0)
        expected = float(g_bar @ g_bar)
        result = _gmm_objective(theta, dat, np.eye(3))
        assert abs(result - expected) < 1e-14


