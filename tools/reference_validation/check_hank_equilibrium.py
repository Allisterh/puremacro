"""Compare the full HANK equilibrium to author code and refine its grids.

No optional reference package is imported. Frozen arrays are regenerated by
hank_equilibrium_reference.py in a separate environment. Exit nonzero on any
failed reference, accounting, or final refinement check.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import time

import numpy as np

from puremacro.models import one_asset_hank as native

ROOT = Path(__file__).resolve().parents[2]
FIELDS = ('pi', 'w', 'Y', 'C', 'A', 'NE', 'r', 'Div', 'Tax')
PROTOCOL = dict(reference_linear_per_unit=1e-6, reference_nonlinear=1e-7,
                reference_policy=1e-7, reference_saving=1e-6,
                reference_calibration=1e-7, markets=1e-8,
                refinement_relative=.01, refinement_absolute=1e-6,
                refinement_calibration=1e-4, upper_grid_mass=1e-8,
                comparison_periods=40)


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def compare_reference():
    folder = ROOT / 'tests/fixtures/hank_equilibrium'
    stem = 'hank_equilibrium_500_7_300'
    manifest = json.loads((folder / f'{stem}.json').read_text(encoding='utf-8'))
    path = folder / f'{stem}.npz'
    if digest(path) != manifest['fixture_sha256']:
        raise ValueError('author-code fixture hash mismatch')
    reference = np.load(path)
    ss = native.calibrate_one_asset_hank()
    checks = []

    def add(name, error, tolerance):
        checks.append(dict(check=name, max_abs_error=float(error), tolerance=float(tolerance),
                           passed=bool(error <= tolerance)))

    for key in ('beta', 'vphi'):
        add(f'steady_{key}', abs(ss.calibration[key] - manifest['steady_state'][key]), 1e-7)
    for key, field in [('a', 'policy_a'), ('c', 'policy_c'), ('n', 'policy_n'), ('D', 'distribution')]:
        add(f'policy_{key}', np.max(np.abs(getattr(ss, field) - reference[key])), 1e-6 if key == 'a' else 1e-7)
    results = {}
    for mode, sign in [('linear', 1), ('nonlinear', 1), ('opposite', -1)]:
        result = native.solve_one_asset_hank(ss, magnitude=sign * manifest['magnitude'], nonlinear=mode != 'linear')
        results[mode] = result
        for key in FIELDS:
            add(f'{mode}_{key}', np.max(np.abs(result.paths[key] - reference[f'{mode}_{key}'])),
                abs(manifest['magnitude']) * 1e-6 if mode == 'linear' else 1e-7)
        add(f'{mode}_markets', result.diagnostics['market_residual_max_abs'], 1e-8)
        if not result.converged:
            add(f'{mode}_feasibility', 1, 0)
    return ss, results, dict(reference_commit=manifest['reference_commit'],
                             reference_fixture_sha256=manifest['fixture_sha256'], checks=checks,
                             diagnostics={k: r.diagnostics for k, r in results.items()},
                             passed=all(row['passed'] for row in checks))


def run(output: Path, convergence: bool):
    output.mkdir(parents=True, exist_ok=True)
    # Save the decision criteria before running any numerical comparison.
    (output / 'protocol.json').write_text(json.dumps(PROTOCOL, indent=2) + '\n', encoding='utf-8')
    start = time.perf_counter()
    ss, results, comparison = compare_reference()
    print(f'Author-code comparison: {comparison["passed"]}', flush=True)
    cases = {}
    cache = {(500, 7, 150.): ss}

    def case(na, ne, horizon, amax=150.):
        key = f'a{na}_e{ne}_T{horizon}_max{amax:g}'
        if key in cases:
            return key
        t = time.perf_counter()
        grid = (na, ne, amax)
        if grid not in cache:
            cache[grid] = native.calibrate_one_asset_hank(n_a=na, n_e=ne, a_max=amax)
        steady = cache[grid]
        result = (results['nonlinear'] if grid == (500, 7, 150.) and horizon == 300 else
                  native.solve_one_asset_hank(steady, horizon=horizon, nonlinear=True))
        result.paths.to_csv(output / f'{key}.csv')
        cases[key] = dict(beta=steady.calibration['beta'], vphi=steady.calibration['vphi'],
                          steady_diagnostics=steady.diagnostics, diagnostics=result.diagnostics,
                          converged=result.converged, seconds=time.perf_counter() - t,
                          first40=result.paths.loc[:39, list(FIELDS)].to_dict(orient='list'))
        print(f'{key}: converged={result.converged}, seconds={cases[key]["seconds"]:.2f}', flush=True)
        return key

    refinements = []

    def refine(label, coarse, fine, required=True):
        left, right = cases[coarse], cases[fine]
        fields = {}
        for name in FIELDS:
            x, y = np.array(left['first40'][name]), np.array(right['first40'][name])
            error = float(np.max(np.abs(x - y)))
            threshold = max(1e-6, .01 * float(np.max(np.abs(y))))
            fields[name] = dict(max_abs_error=error, tolerance=threshold, passed=error <= threshold)
        calibration = {key: abs(left[key] - right[key]) for key in ('beta', 'vphi')}
        passed = all(row['passed'] for row in fields.values()) and max(calibration.values()) <= 1e-4
        refinements.append(dict(label=label, coarse=coarse, fine=fine, fields=fields,
                                calibration_changes=calibration, passed=passed, required=required))
        print(f'{label}: {passed}; calibration changes {calibration}', flush=True)

    case(500, 7, 300)
    if convergence:
        refine('assets_250_to_500', case(250, 7, 300), case(500, 7, 300), required=False)
        refine('assets_500_to_1000', case(500, 7, 300), case(1000, 7, 300))
        # More extreme skill states require a wider asset bound. Compare all
        # income refinements on the same bound, then check that bound itself.
        refine('asset_bound_150_to_300', case(1000, 7, 300), case(1000, 7, 300, 300.))
        refine('income_7_to_11', case(1000, 7, 300, 300.), case(1000, 11, 300, 300.), required=False)
        refine('income_11_to_15', case(1000, 11, 300, 300.), case(1000, 15, 300, 300.), required=False)
        refine('asset_bound_300_to_600', case(1000, 15, 300, 300.), case(1000, 15, 300, 600.))
        # The initial 11-to-15-state comparison missed the registered 1%
        # criterion. Keep that failed comparison and extend the ladder.
        refine('income_15_to_21', case(1000, 15, 300, 600.), case(1000, 21, 300, 600.), required=False)
        refine('income_21_to_31', case(1000, 21, 300, 600.), case(1000, 31, 300, 600.))
        refine('assets_at_31_income_states', case(500, 31, 300, 600.), case(1000, 31, 300, 600.))
        refine('horizon_at_31_income_states', case(1000, 31, 300, 600.), case(1000, 31, 600, 600.))
        refine('horizon_150_to_300', case(500, 7, 150), case(500, 7, 300), required=False)
        refine('horizon_300_to_600', case(500, 7, 300), case(500, 7, 600))
    record = dict(protocol=PROTOCOL, author_comparison=comparison, cases=cases,
                   refinements=refinements, seconds=time.perf_counter() - start,
                   native_source_sha256=digest(ROOT / 'puremacro/models/one_asset_hank.py'))
    record['passed'] = (comparison['passed'] and all(v['converged'] for v in cases.values())
                        and all(row['passed'] for row in refinements if row['required'])
                        and all(v['diagnostics'].get('upper_grid_mass', 0) <= 1e-8 for v in cases.values()))
    (output / 'hank_equilibrium_validation.json').write_text(json.dumps(record, indent=2) + '\n', encoding='utf-8')
    return record


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--convergence', action='store_true')
    args = parser.parse_args()
    record = run(args.output, args.convergence)
    print(f'Overall: {record["passed"]}; {record["seconds"]:.2f} seconds')
    raise SystemExit(0 if record['passed'] else 1)


if __name__ == '__main__':
    main()
